#!/usr/bin/env node
/**
 * Emit verify/js_slab_exceptions.bend: per-slice (amount, rate) pairs where
 * Math.round((amount/100)*rate) !== Math.round((amount*rate)/100) for FY2026 slabs
 * on taxables 0..1_800_000. Bend has no IEEE floats; these overrides emulate JS.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { calculateSlabBreakdown } from '../src/utils/taxEngine.js'
import { calculateTaxSlabs2026, getTaxFreeThreshold2026 } from '../src/utils/taxSlabs2026.js'

const root = path.dirname(fileURLToPath(import.meta.url))
const outPath = path.join(root, '..', 'verify', 'js_slab_exceptions.bend')

const threshold = getTaxFreeThreshold2026({ category: 'general', age: null, parentOfDisabled: false })
const slabs = calculateTaxSlabs2026(threshold)

const jsCut = (amount, rate) => Math.round((amount / 100) * rate)
const intCut = (amount, rate) => Math.round((amount * rate) / 100)

const special = new Map()
for (let taxable = 0; taxable <= 1_800_000; taxable++) {
  const breakdown = calculateSlabBreakdown(taxable, slabs, 'gen')
  for (const row of breakdown) {
    const amount = row.slabAmount
    const rate = row.slabPercentage
    if (amount <= 0 || rate <= 0) continue
    if (jsCut(amount, rate) !== intCut(amount, rate)) {
      const key = `${amount}:${rate}`
      if (!special.has(key)) special.set(key, jsCut(amount, rate))
    }
  }
}

const byAmount = new Map()
for (const [key, value] of special) {
  const [amount, rate] = key.split(':').map(Number)
  if (!byAmount.has(amount)) byAmount.set(amount, [])
  byAmount.get(amount).push([rate, value])
}
const amounts = [...byAmount.keys()].sort((a, b) => a - b)

let body = `# AUTO-GENERATED by scripts/gen-bend-slab-cut.mjs — do not edit.
# ${special.size} (amount, rate) pairs where integer ((amount*rate)+50)/100 ≠ JS Math.round((amount/100)*rate).

def js_slab_cut(amount, rate):
  switch amount:
`

for (const amount of amounts) {
  const rates = byAmount.get(amount).sort((a, b) => a[0] - b[0])
  body += `    case ${amount}:\n      switch rate:\n`
  for (const [rate, value] of rates) {
    body += `        case ${rate}:\n          return ${value}\n`
  }
  body += `        case _:\n          return ((amount * rate) + 50) / 100\n`
}

body += `    case _:\n      return ((amount * rate) + 50) / 100
`

fs.writeFileSync(outPath, body)
console.log(`Wrote ${outPath} (${special.size} exceptions across ${amounts.length} amounts)`)